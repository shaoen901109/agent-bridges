# encoding: utf-8
"""Power Automate Desktop Agent Bridge 的 MCP server（stdio transport）。

只是 console.py / designer.py / runs.py 的一層薄殼。

啟動方式：
    python -m pad_bridge.mcp_server
環境變數：
    PAD_BRIDGE_AUTO_CONFIRM   設為 1 時，bridge 會替「自己剛觸發的同名流程」按下
                              PAD 的「外部來源正在嘗試執行以下流程 → 繼續」。預設關閉。
"""

from __future__ import annotations

import json
import traceback
from typing import Any, Callable, Dict, List, Optional

try:
    # mcp SDK 2.x：FastMCP 已改名為 MCPServer
    from mcp.server.mcpserver import MCPServer as _ServerClass
except ImportError:  # pragma: no cover - 相容 mcp SDK 1.x
    from mcp.server.fastmcp import FastMCP as _ServerClass

from . import console, designer, runs
from .uia import PadUiError

mcp = _ServerClass(
    "pad-bridge",
    instructions=(
        "Run, inspect, create and edit Power Automate Desktop (PAD) desktop flows on this Windows machine. "
        "Flows run in attended mode on the user's desktop: flows that use mouse/keyboard/UI actions take over "
        "the screen, and only one flow can run at a time. pad_create_flow / pad_update_flow / pad_get_flow_script "
        "drive the PAD designer with real keyboard and mouse input, so tell the user before calling them and ask "
        "them not to touch the PC meanwhile. 前提：使用者已安裝 Power Automate 並登入。"
        "若回傳 awaiting_confirmation，請使用者在 PAD 的確認框按「繼續」，不要自行想辦法繞過。"
    ),
)


def _dump(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, default=str, indent=1)


def _safe(fn: Callable[[], Any]) -> str:
    try:
        return _dump(fn())
    except designer.ScriptError as exc:
        return f"PAD_SCRIPT_ERROR\n{exc}"
    except PadUiError as exc:
        return f"PAD_UI_ERROR\n{exc}"
    except ValueError as exc:
        return f"PAD_BAD_ARGUMENT\n{exc}"
    except Exception as exc:  # pragma: no cover - 意外錯誤要讓 agent 看得到細節
        return f"PAD_BRIDGE_FAILED\n{exc}\n{traceback.format_exc(limit=5)}"


# --- 查詢 -------------------------------------------------------------------


@mcp.tool()
def pad_list_flows() -> str:
    """List the desktop flows in the PAD console with their run status.

    列出 console 裡的所有桌面流程（名稱、執行狀態、修改時間、已知的流程 ID）與登入帳號。
    Opens the PAD console if it is not running. Call this first.
    """
    return _safe(console.list_flows)


@mcp.tool()
def pad_get_flow_script(flow_name: str) -> str:
    """Read a flow's Robin script (the text form of its actions) plus its variables.

    讀出流程 Main 子流程的 Robin 腳本、輸入／輸出／流程變數、子流程清單。
    會短暫開啟 PAD 設計工具並用鍵盤複製（使用者的剪貼簿會還原）。
    Use it to learn Robin syntax from the user's existing flows before writing a new one.
    """
    return _safe(lambda: designer.get_flow_script(flow_name))


@mcp.tool()
def pad_get_run(run_id: str, action_tail: int = 10) -> str:
    """Get status, output variables, failed actions and the last actions of a run.

    run_id 來自 pad_run_flow / pad_list_runs。失敗時 not_succeeded_actions 會列出出錯的動作與錯誤訊息。
    """

    def _get():
        run_dir = runs.find_run_dir(run_id)
        if not run_dir:
            raise ValueError(f"找不到執行紀錄 {run_id}")
        return runs.summarize_run(run_dir, action_tail=action_tail)

    return _safe(_get)


@mcp.tool()
def pad_list_runs(flow_name: Optional[str] = None, limit: int = 10) -> str:
    """List recent local runs (newest first), optionally only for one flow.

    列出本機最近的執行紀錄：狀態、起訖時間、輸出變數。
    """
    return _safe(lambda: runs.list_runs(flow_name=flow_name, limit=limit))


@mcp.tool()
def pad_get_dialogs() -> str:
    """Show dialogs currently open in the PAD console (run confirmation, errors, flow outputs).

    流程卡住或逾時時用來看 console 停在哪個對話框。
    """
    return _safe(console.get_dialogs)


@mcp.tool()
def pad_dismiss_dialogs() -> str:
    """Close informational PAD console dialogs (error messages and flow-output popups).

    只關閉錯誤與輸出對話框；不會替使用者按「繼續執行」確認框。
    """
    return _safe(console.dismiss_dialogs)


@mcp.tool()
def pad_search_actions(query: str, limit: int = 30) -> str:
    """Search PAD's action catalog (the designer's Actions pane) by display name.

    以動作面板的顯示名稱搜尋（介面是繁中，請用中文關鍵字，例如「取代」「PowerShell」「Excel」「下載」）。
    回傳 action_id（Robin 的 模組.動作群組）與名稱。會短暫開啟暫存流程 _pad_bridge_scratch 的設計工具。
    """
    return _safe(lambda: designer.search_actions(query, limit))


@mcp.tool()
def pad_action_template(query: str, action_id: Optional[str] = None) -> str:
    """Get the exact Robin syntax of one action, generated by PAD itself with default parameters.

    寫腳本前不確定某動作的名稱或參數時用這個，不要猜。query 是動作面板搜尋字；
    有多個結果時用 action_id（來自 pad_search_actions）指定。回傳的 robin 範本把參數換成需要的值即可使用；
    Robin 中空字串寫成 ``，文字常值寫成 $'''...'''。
    若動作有必填參數，PAD 不讓空白存檔，會回報錯誤與對話框內容。
    """
    return _safe(lambda: designer.action_template(query, action_id))


# --- 執行 -------------------------------------------------------------------


@mcp.tool()
def pad_run_flow(
    flow_name: Optional[str] = None,
    inputs: Optional[Dict[str, Any]] = None,
    wait: bool = True,
    timeout_s: float = 600,
    flow_id: Optional[str] = None,
) -> str:
    """Run a desktop flow and (by default) wait for it to finish.

    flow_name: 流程名稱（或改給 flow_id）。
    inputs: {"輸入變數的外部名稱": 值}，值只能是文字、數字、布林；沒給的輸入會用預設值或讓 PAD 跳窗詢問。
        大量資料請寫成檔案，傳檔案路徑。
    wait: False 時一開始執行就回傳 run_id，之後用 pad_get_run 查。
    回傳 status（Succeeded / Failed / Cancelled / still_running / awaiting_confirmation / error / not_found）、
    outputs（輸出變數）、not_succeeded_actions（失敗動作與錯誤訊息）、run_id、log_dir。
    """
    return _safe(lambda: console.run_flow(flow_name, flow_id, inputs, wait, timeout_s))


@mcp.tool()
def pad_stop_flow(flow_name: str) -> str:
    """Stop a running desktop flow. 停止執行中的流程。"""
    return _safe(lambda: console.stop_flow(flow_name))


# --- 建立與修改 ---------------------------------------------------------------



@mcp.tool()
def pad_create_flow(
    flow_name: str,
    script: str = "",
    inputs: Optional[List[Dict[str, Any]]] = None,
    outputs: Optional[List[Dict[str, Any]]] = None,
    power_fx: bool = False,
) -> str:
    """Create a new desktop flow from a Robin script, with input/output variables, and save it.

    script: Robin 腳本（PAD 動作的文字格式，與在設計工具裡複製動作得到的文字相同）。
        預設 power_fx=False，用傳統語法：文字常值 $'''...'''、變數插值 %Var%。
    inputs / outputs: 變數規格清單，每項 {"name": 變數名, "type": "text"|"number"|"boolean",
        "default": 預設值(僅輸入), "description": 說明, "external_name": 外部名稱(預設同 name),
        "optional": bool(僅輸入), "sensitive": bool}。已存在的同名變數會跳過。
    會用真實鍵盤滑鼠操作 PAD 設計工具約 20–60 秒，期間請使用者不要操作電腦。
    """
    return _safe(lambda: designer.create_flow(flow_name, script, inputs, outputs, power_fx))


@mcp.tool()
def pad_update_flow(
    flow_name: str,
    script: Optional[str] = None,
    inputs: Optional[List[Dict[str, Any]]] = None,
    outputs: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """Replace an existing flow's Main script and/or add missing input/output variables, then save.

    script 為 None 時只補變數不動動作；給字串時會「整段取代」Main 子流程的所有動作，
    修改前請先用 pad_get_flow_script 取得原腳本再改。
    inputs / outputs: 變數規格清單，每項 {"name": 變數名, "type": "text"|"number"|"boolean",
        "default": 預設值(僅輸入), "description": 說明, "external_name": 外部名稱(預設同 name),
        "optional": bool(僅輸入), "sensitive": bool}。已存在的同名變數會跳過。
    """
    return _safe(lambda: designer.update_flow(flow_name, script, inputs, outputs))


def main() -> None:
    mcp.run()


if __name__ == "__main__":
    main()
